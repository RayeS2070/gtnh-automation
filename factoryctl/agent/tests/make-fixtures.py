#!/usr/bin/env python3
"""Turns the server's test data (real dumps from the game) into Lua tables for the agent's
tests: local Lua has no JSON parser. Run from factoryctl/agent after the data changes:
  python3 tests/make-fixtures.py
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE.parent.parent / 'server' / 'tests' / 'data'


def lua(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        # JSON string escapes for quote and backslash are Lua's too; labels have no control chars.
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, dict):
        return '{' + ', '.join(f'{k} = {lua(x)}' for k, x in sorted(v.items())) + '}'
    raise TypeError(v)


for name in ('me-sample', 'cpus'):
    rows = [json.loads(line) for line in (DATA / f'{name}.jsonl').read_text(encoding='utf-8').splitlines()]
    out = HERE / 'fixtures' / f"{name.replace('-', '_')}.lua"
    body = ',\n'.join('    ' + lua(r) for r in rows)
    out.write_text(f'-- Generated by tests/make-fixtures.py from server/tests/data/{name}.jsonl.\n'
                   f'return {{\n{body},\n}}\n', encoding='utf-8')
    print(out.name, len(rows))
